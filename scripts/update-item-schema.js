#!/usr/bin/env node
import fs from "node:fs/promises";

const DEFAULT_SCHEMA_URL = "https://pub.drednot.io/prod/econ/item_schema.json";
const OUTPUT_FILE = new URL("../src/data/item-schema.js", import.meta.url);

async function main() {
  const source = process.argv[2] || process.env.DRED_ITEM_SCHEMA_URL || DEFAULT_SCHEMA_URL;
  const schema = await loadSchema(source);
  validateSchema(schema, source);
  const generated = renderModule(schema, source);
  await fs.writeFile(OUTPUT_FILE, generated, "utf8");
  console.log(`updated ${new URL(OUTPUT_FILE).pathname} from ${source} (${schema.length} items)`);
}

async function loadSchema(source) {
  if (/^https?:\/\//i.test(source)) {
    if (typeof fetch !== "function") throw new Error("global fetch is required to fetch item schema URLs");
    const response = await fetch(source, { headers: { accept: "application/json" } });
    if (!response.ok) throw new Error(`item schema fetch failed: ${response.status} ${response.statusText}`);
    return response.json();
  }
  return JSON.parse(await fs.readFile(source, "utf8"));
}

function validateSchema(schema, source) {
  if (!Array.isArray(schema)) throw new Error(`item schema from ${source} must be an array`);
  for (const [index, item] of schema.entries()) {
    if (!item || typeof item !== "object") throw new Error(`item schema row ${index} must be an object`);
    if (!Number.isFinite(Number(item.id))) throw new Error(`item schema row ${index} has invalid id`);
    if (typeof item.name !== "string") throw new Error(`item schema row ${index} has invalid name`);
  }
}

function renderModule(schema, source) {
  const json = JSON.stringify(schema, null, 2).replace(/[\u007f-\uffff]/g, (char) => {
    return `\\u${char.charCodeAt(0).toString(16).padStart(4, "0")}`;
  });
  return `// Generated by scripts/update-item-schema.js from ${source}. Do not edit manually.\n\nexport const ITEM_SCHEMA = Object.freeze(${json});\n`;
}

main().catch((error) => {
  console.error(error?.stack || error?.message || String(error));
  process.exitCode = 1;
});
